//! Read-only pool/network inventory and conservative, separate disk deletion.

use virt::{connect::Connect, storage_pool::StoragePool, storage_vol::StorageVol};
use crate::{error::{Error, Result}, xml};

/// A storage volume and its allocated/logical sizes, in bytes.
pub struct Volume {
    pub name: String,
    pub capacity: u64,
    pub allocation: u64,
    pub managed: bool,
}

/// Pool inventory; only active directory pools can receive newly created disks.
pub struct Pool {
    pub name: String,
    pub active: bool,
    pub directory: bool,
    pub capacity: u64,
    pub available: u64,
    pub volumes: Vec<Volume>,
}

/// Existing libvirt networks; host interfaces are never reconfigured by this app.
pub struct Network {
    pub name: String,
    pub active: bool,
    pub autostart: bool,
    pub bridge: String,
}

/// Enumerates pool contents and propagates access errors rather than hiding them.
pub fn pools(conn: &Connect) -> Result<Vec<Pool>> {
    let mut result = Vec::new();
    for pool in conn.list_all_storage_pools(0)? {
        let active = pool.is_active()?;
        let root = xml::parse(&pool.get_xml_desc(0)?)?;
        let mut item = Pool { name: pool.get_name()?, active, directory: xml::attr(&root, "type") == "dir", capacity: 0, available: 0, volumes: Vec::new() };
        if active {
            let info = pool.get_info()?;
            item.capacity = info.capacity;
            item.available = info.available;
            for volume in pool.list_all_volumes(0)? {
                let name = volume.get_name()?;
                let info = volume.get_info()?;
                item.volumes.push(Volume { managed: managed_name(&name), name, capacity: info.capacity, allocation: info.allocation });
            }
            item.volumes.sort_by(|a, b| a.name.cmp(&b.name));
        }
        result.push(item);
    }
    result.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(result)
}

/// Reads network facts used by the inventory and the creation wizard.
pub fn networks(conn: &Connect) -> Result<Vec<Network>> {
    let mut result = Vec::new();
    for network in conn.list_all_networks(0)? {
        let root = xml::parse(&network.get_xml_desc(0)?)?;
        result.push(Network {
            name: network.get_name()?, active: network.is_active()?, autostart: network.get_autostart()?,
            bridge: root.get_child("bridge").map_or("", |node| xml::attr(node, "name")).to_string(),
        });
    }
    result.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(result)
}

/// Recognizes the reserved names generated by this application, never arbitrary disks.
pub fn managed_name(name: &str) -> bool {
    name.strip_prefix("virtualvmweb-").and_then(|s| s.strip_suffix(".qcow2"))
        .is_some_and(|id| uuid::Uuid::parse_str(id).is_ok())
}

/// Detects references including alternative symlink spellings of a local file.
fn references(node: &xmltree::Element, target: &std::path::Path) -> bool {
    let matches = |value: &str| std::fs::canonicalize(value).is_ok_and(|path| path == target);
    node.attributes.values().any(|value| value.starts_with('/') && matches(value))
        || node.get_text().is_some_and(|value| value.starts_with('/') && matches(&value))
        || node.children.iter().filter_map(xmltree::XMLNode::as_element).any(|child| references(child, target))
}

/// Recognizes libvirt volume-backed disks that name a pool/volume instead of a file path.
fn volume_reference(node: &xmltree::Element, pool: &str, volume: &str) -> bool {
    (xml::attr(node, "pool") == pool && xml::attr(node, "volume") == volume)
        || node.children.iter().filter_map(xmltree::XMLNode::as_element).any(|child| volume_reference(child, pool, volume))
}

/// Deletes only an explicitly named, detached application disk after fail-closed reference checks.
pub fn delete_volume(conn: &Connect, pool_name: &str, name: &str, confirmation: &str) -> Result<()> {
    if !managed_name(name) || confirmation != name {
        return Err(Error::bad("Vain sovelluksen luoman levyn voi poistaa. Kirjoita levyn koko nimi vahvistukseksi."));
    }
    let pool = StoragePool::lookup_by_name(conn, pool_name)?;
    if xml::attr(&xml::parse(&pool.get_xml_desc(0)?)?, "type") != "dir" || !pool.is_active()? {
        return Err(Error::conflict("Poisto vaatii aktiivisen hakemistopoolin."));
    }
    let volume = StorageVol::lookup_by_name(&pool, name)?;
    let path = std::fs::canonicalize(volume.get_path()?).map_err(Error::internal)?;
    for dom in conn.list_all_domains(0)? {
        if dom.has_managed_save(0)? || !dom.list_all_snapshots(0)?.is_empty() {
            return Err(Error::conflict("Levyn turvallista poistoa ei voida varmistaa tallennettujen tilojen tai snapshotien vuoksi."));
        }
        let live = xml::parse(&dom.get_xml_desc(0)?)?;
        let inactive = if dom.is_persistent()? { Some(xml::parse(&dom.get_xml_desc(virt::sys::VIR_DOMAIN_XML_INACTIVE)?)?) } else { None };
        if references(&live, &path) || volume_reference(&live, pool_name, name)
            || inactive.as_ref().is_some_and(|root| references(root, &path) || volume_reference(root, pool_name, name)) {
            return Err(Error::conflict("Levy on yhä virtuaalikoneen käytössä."));
        }
    }
    for other_pool in conn.list_all_storage_pools(0)? {
        if !other_pool.is_active()? {
            return Err(Error::conflict("Aktivoi kaikki tallennuspoolit, jotta levyn viittaukset voidaan tarkistaa."));
        }
        other_pool.refresh(0)?;
        for other in other_pool.list_all_volumes(0)? {
            let root = xml::parse(&other.get_xml_desc(0)?)?;
            if let Some(backing) = root.get_child("backingStore") {
                let relative = backing.get_child("path").and_then(|p| p.get_text()).is_some_and(|p| !p.is_empty() && !p.starts_with('/'));
                if relative || references(backing, &path) {
                    return Err(Error::conflict("Levy on toisen levykuvan pohjalevy."));
                }
            }
        }
    }
    volume.delete(0)?;
    tracing::info!(pool = pool_name, volume = name, "administrator deleted detached disk");
    Ok(())
}

